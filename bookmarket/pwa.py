"""
Progressive Web App endpoints:

  /sw.js                 service worker (push + offline shell), served from the site root
  /manifest.webmanifest  web app manifest (name, icons, theme colours, shortcuts)
  /offline/              page the service worker shows when a navigation fails offline

The manifest and service worker are generated by views (not served as plain static
files) so icon/asset URLs go through `static()` - in production those are
content-hashed by WhiteNoise's manifest storage and change on every deploy.
"""
import hashlib
import json

from django.conf import settings
from django.http import HttpResponse, JsonResponse
from django.shortcuts import render
from django.templatetags.static import static
from django.urls import reverse
from django.views.decorators.cache import never_cache

THEME_COLOR = '#1f3a5f'
BACKGROUND_COLOR = '#1f3a5f'


def _precache_urls():
    return [
        reverse('offline'),
        static('favicon.svg'),
        static('img/icons/icon-192.png'),
        static('js/offline.js'),
    ]


@never_cache
def service_worker(request):
    """
    Serves static/js/notifications-sw.js at /sw.js. A service worker's scope is
    limited to the path it is served from, so serving it from /static/js/ would
    cover nothing useful; Service-Worker-Allowed keeps the root scope explicit.

    Placeholders in the file are filled here; the cache version is a hash of the
    precache list plus PWA_VERSION, so a deploy that changes any hashed static
    file automatically rolls the cache over.
    """
    sw_path = settings.BASE_DIR / 'static' / 'js' / 'notifications-sw.js'
    try:
        source = sw_path.read_text()
    except OSError:
        source = '// notifications-sw.js not found\n'

    urls = _precache_urls()
    version_seed = '|'.join(urls) + '|' + str(getattr(settings, 'PWA_VERSION', '1'))
    version = hashlib.sha1(version_seed.encode()).hexdigest()[:10]
    source = (source
              .replace('__SW_VERSION__', version)
              .replace('__PRECACHE__', json.dumps(urls)))

    response = HttpResponse(source, content_type='application/javascript')
    response['Service-Worker-Allowed'] = '/'
    return response


