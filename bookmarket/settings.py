# ---- File storage ---------------------------------------------------------------------------------------------
# Default: local disk (MEDIA_ROOT / PRIVATE_MEDIA_ROOT), fine for local development. On hosts whose disk is
# read-only or wiped on every deploy (Wasmer Edge) use an S3-compatible bucket (Backblaze B2, Cloudflare R2, ...) instead:
#   S3_ENDPOINT_URL, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY, S3_REGION (default 'auto')
#   S3_PUBLIC_BUCKET (+ S3_PUBLIC_DOMAIN) -> book photos and avatars. With S3_PUBLIC_DOMAIN the bucket is public and
#                                            photos load from that domain; WITHOUT it the bucket can stay private and
#                                            photos are served through signed, expiring links (no public bucket needed)
#   S3_PRIVATE_BUCKET                     -> ID proofs, paid digital books, chat + dispute files (NOT public)
# Either bucket can be set on its own; whichever is unset keeps using local disk.
def _s3_client_config():
    """botocore Config for S3-compatible stores. Newer boto3 adds checksum headers that Backblaze B2 (and some other
    non-AWS stores) reject; 'when_required' turns that off. Older botocore versions don't know those options -> skip."""
    from botocore.config import Config
    style = os.environ.get('S3_ADDRESSING_STYLE', '').strip()  # 'path' or 'virtual' if your provider needs it; blank = auto
    kwargs = {'signature_version': 's3v4'}   # B2 / R2 only accept SigV4 (also for presigned links)
    if style:
        kwargs['s3'] = {'addressing_style': style}
    try:
        return Config(request_checksum_calculation='when_required', response_checksum_validation='when_required', **kwargs)
    except TypeError:
        return Config(**kwargs)


